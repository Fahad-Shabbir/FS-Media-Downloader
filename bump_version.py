import os
import sys
import re
from datetime import datetime

ROOT_DIR = os.path.dirname(os.path.abspath(__file__))
UPDATER_PATH = os.path.join(ROOT_DIR, "updater.py")
VERSION_INFO_PATH = os.path.join(ROOT_DIR, "version_info.txt")
INSTALLER_PATH = os.path.join(ROOT_DIR, "installer.iss")
RELEASE_NOTES_PATH = os.path.join(ROOT_DIR, "RELEASE_NOTES.txt")
CURRENT_VER_PATH = os.path.join(ROOT_DIR, "current_version.txt")


def read_current_version():
    """Reads APP_VERSION from updater.py."""
    if not os.path.isfile(UPDATER_PATH):
        raise FileNotFoundError(f"updater.py not found at {UPDATER_PATH}")
    
    with open(UPDATER_PATH, "r", encoding="utf-8") as f:
        content = f.read()

    match = re.search(r'APP_VERSION\s*=\s*["\'](\d+)\.(\d+)\.(\d+)["\']', content)
    if not match:
        raise ValueError("Could not parse APP_VERSION from updater.py")

    major, minor, patch = map(int, match.groups())
    return major, minor, patch, content


def bump(major, minor, patch, bump_type):
    """Calculates new version tuple based on bump_type."""
    b_type = (bump_type or "patch").strip().lower()
    if b_type == "major":
        return major + 1, 0, 0
    elif b_type == "minor":
        return major, minor + 1, 0
    elif b_type == "none":
        return major, minor, patch
    elif b_type == "patch":
        return major, minor, patch + 1
    else:
        raise ValueError(f"Unknown bump type '{bump_type}'. Choose patch, minor, major, or none.")


def update_updater_file(content, new_ver_str):
    """Replaces APP_VERSION in updater.py."""
    new_content = re.sub(
        r'APP_VERSION\s*=\s*["\']\d+\.\d+\.\d+["\']',
        f'APP_VERSION = "{new_ver_str}"',
        content,
        count=1
    )
    with open(UPDATER_PATH, "w", encoding="utf-8") as f:
        f.write(new_content)


def generate_version_info(major, minor, patch):
    """Generates PyInstaller version_info.txt for Windows File Details."""
    ver_tuple = (major, minor, patch, 0)
    ver_str = f"{major}.{minor}.{patch}.0"
    prod_ver_str = f"{major}.{minor}.{patch}"

    content = f"""# UTF-8
#
# Auto-generated by bump_version.py for PyInstaller Windows Version Info Resource
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={ver_tuple},
    prodvers={ver_tuple},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo(
      [
        StringTable(
          '040904B0',
          [
            StringStruct('CompanyName', 'Fahad Shabbir'),
            StringStruct('FileDescription', 'FS Media Downloader'),
            StringStruct('FileVersion', '{ver_str}'),
            StringStruct('InternalName', 'FS Media Downloader'),
            StringStruct('LegalCopyright', 'Copyright (C) 2026 Fahad Shabbir'),
            StringStruct('OriginalFilename', 'FS Media Downloader.exe'),
            StringStruct('ProductName', 'FS Media Downloader'),
            StringStruct('ProductVersion', '{prod_ver_str}')
          ]
        )
      ]
    ),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""
    with open(VERSION_INFO_PATH, "w", encoding="utf-8") as f:
        f.write(content)


def update_installer_iss(new_ver_str):
    """Keeps installer.iss MyAppVersion in sync if the file exists."""
    if not os.path.isfile(INSTALLER_PATH):
        return
    with open(INSTALLER_PATH, "r", encoding="utf-8") as f:
        content = f.read()

    new_content = re.sub(
        r'#define\s+MyAppVersion\s+["\'][^"\']+["\']',
        f'#define MyAppVersion "{new_ver_str}"',
        content
    )
    with open(INSTALLER_PATH, "w", encoding="utf-8") as f:
        f.write(new_content)


def append_release_notes(new_ver_str, summary):
    """Appends an entry to RELEASE_NOTES.txt."""
    today = datetime.now().strftime("%Y-%m-%d %H:%M")
    note_text = summary.strip() if summary else f"Release build v{new_ver_str}"

    header = ""
    if not os.path.isfile(RELEASE_NOTES_PATH):
        header = "FS Media Downloader - Release Notes & Build History\n" + ("=" * 55) + "\n\n"

    entry = f"[{today}] v{new_ver_str}: {note_text}\n"

    with open(RELEASE_NOTES_PATH, "a", encoding="utf-8") as f:
        if header:
            f.write(header)
        f.write(entry)


def main():
    bump_type = "patch"
    summary = ""

    if len(sys.argv) > 1:
        bump_type = sys.argv[1]
    if len(sys.argv) > 2:
        summary = " ".join(sys.argv[2:])

    old_major, old_minor, old_patch, content = read_current_version()
    new_major, new_minor, new_patch = bump(old_major, old_minor, old_patch, bump_type)

    old_ver_str = f"{old_major}.{old_minor}.{old_patch}"
    new_ver_str = f"{new_major}.{new_minor}.{new_patch}"

    # 1. Update updater.py
    update_updater_file(content, new_ver_str)

    # 2. Generate version_info.txt
    generate_version_info(new_major, new_minor, new_patch)

    # 3. Update installer.iss
    update_installer_iss(new_ver_str)

    # 4. Append to RELEASE_NOTES.txt
    append_release_notes(new_ver_str, summary)

    # 5. Write current_version.txt for build scripts
    with open(CURRENT_VER_PATH, "w", encoding="utf-8") as f:
        f.write(new_ver_str)

    print(f"[Version] {old_ver_str} -> {new_ver_str} (bump: {bump_type})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
